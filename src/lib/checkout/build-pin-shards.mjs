#!/usr/bin/env node
/*
 * Builds static/pin/<3 digits>.json — the PIN → city/state shards the checkout
 * uses to prefill City and State (roadmap S5). Not part of the app bundle:
 * nothing imports this file; run it by hand when refreshing the data.
 *
 * Source: GeoNames postal codes for India (https://download.geonames.org/export/zip/IN.zip),
 * licensed CC BY 4.0 — credit GeoNames (https://www.geonames.org). The credit
 * ships in static/pin/CREDITS.txt and next to the autofill hint on /checkout.
 *
 *   curl -O https://download.geonames.org/export/zip/IN.zip && unzip IN.zip IN.txt
 *   node src/lib/checkout/build-pin-shards.mjs --src=IN.txt [--out=static/pin]
 *   node src/lib/checkout/build-pin-shards.mjs --prefixes-only [--out=static/pin]   (module only, from the shards on disk)
 *
 * It also writes src/lib/checkout/pin-prefixes.js (--prefixes=<path>): the set
 * of prefixes that HAVE a shard, so lookupPin never fetches one that would 404
 * (a typo or an unassigned prefix would otherwise log a console error and
 * count in RUM / error monitoring).
 *
 * Shard format (one file per first-3-digits prefix, keys = last 3 digits):
 *   static/pin/560.json → {"001":["Bengaluru","Karnataka"],"002":[…],…}
 * City = the most common district (admin name 2) listed for the PIN; State =
 * the most common state, mapped to the official name ($shared canonicalState;
 * the build fails on any state it cannot map). Leh and Kargil are listed under
 * Jammu & Kashmir in the source; they are Ladakh since 2019.
 * Only PINs matching /^[1-8]\d{5}$/ (9xxxxx is the Army Postal Service).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalState } from '../../../cms/src/commerce/shared/validate.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const arg = (name, fallback) => {
	const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
	return hit ? hit.slice(name.length + 3) : fallback;
};

const SRC = arg('src', 'IN.txt');
const OUT = path.resolve(ROOT, arg('out', 'static/pin'));
const PREFIXES_OUT = path.resolve(ROOT, arg('prefixes', 'src/lib/checkout/pin-prefixes.js'));

/** src/lib/checkout/pin-prefixes.js for the shards in OUT. */
function writePrefixes() {
	const list = fs
		.readdirSync(OUT)
		.filter((f) => /^\d{3}\.json$/.test(f))
		.map((f) => f.slice(0, 3))
		.sort();
	const src = [
		'/*',
		' * GENERATED by src/lib/checkout/build-pin-shards.mjs — do not edit.',
		' * The 3-digit PIN prefixes that have a shard in static/pin/ (GeoNames, CC BY 4.0):',
		' * pin.js fetches /pin/<prefix>.json only for these, so no lookup ever 404s.',
		' */',
		`export const PIN_PREFIXES = new Set('${list.join(' ')}'.split(' '));`,
		''
	].join('\n');
	fs.writeFileSync(PREFIXES_OUT, src);
	console.log(`build-pin-shards: ${list.length} prefixes → ${path.relative(ROOT, PREFIXES_OUT)}`);
}

if (process.argv.includes('--prefixes-only')) {
	writePrefixes();
	process.exit(0);
}
const PIN = /^[1-8]\d{5}$/;
const LADAKH_DISTRICTS = new Set(['leh', 'leh ladakh', 'kargil']);

/** Most frequent value (ties → first seen). */
function mode(counts) {
	let best = null;
	let n = 0;
	for (const [value, c] of counts) {
		if (c > n) {
			best = value;
			n = c;
		}
	}
	return best;
}

function bump(map, key) {
	map.set(key, (map.get(key) || 0) + 1);
}

const rows = fs.readFileSync(SRC, 'utf8').split('\n');
/** pin → { cities: Map, states: Map } */
const pins = new Map();
const unmapped = new Set();
for (const line of rows) {
	if (!line.trim()) continue;
	const f = line.split('\t');
	const [country, pin, , stateRaw, , district] = f;
	if (country !== 'IN' || !PIN.test(pin)) continue;
	const city = (district || '').trim();
	let state = canonicalState(stateRaw || '');
	if (!state) {
		unmapped.add(stateRaw);
		continue;
	}
	if (LADAKH_DISTRICTS.has(city.toLowerCase())) state = 'Ladakh';
	let entry = pins.get(pin);
	if (!entry) pins.set(pin, (entry = { cities: new Map(), states: new Map() }));
	if (city && city.toUpperCase() !== 'NA') bump(entry.cities, city);
	bump(entry.states, state);
}
if (unmapped.size) {
	console.error('build-pin-shards: unmapped states:', [...unmapped].join(', '));
	process.exit(1);
}

/** prefix → { suffix: [city, state] } */
const shards = new Map();
for (const [pin, { cities, states }] of [...pins].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
	const prefix = pin.slice(0, 3);
	if (!shards.has(prefix)) shards.set(prefix, {});
	shards.get(prefix)[pin.slice(3)] = [mode(cities) || '', mode(states)];
}

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) if (/^\d{3}\.json$/.test(f)) fs.unlinkSync(path.join(OUT, f));
let bytes = 0;
for (const [prefix, data] of shards) {
	const json = JSON.stringify(data);
	bytes += json.length;
	fs.writeFileSync(path.join(OUT, prefix + '.json'), json);
}
console.log(`build-pin-shards: ${pins.size} PINs in ${shards.size} shards (${Math.round(bytes / 1024)} KB) → ${path.relative(ROOT, OUT)}`);
writePrefixes();
